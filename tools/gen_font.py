#!/usr/bin/env python3
"""Subsets a BDF bitmap font into C source: every character the given files use, plus ASCII."""
import argparse
import sys

class FontError(Exception):
    pass


def collect_chars(paths):
    wanted = set()
    for path in paths:
        with open(path, 'r', encoding='utf-8') as f:
            text = f.read()
        for ch in text:
            cp = ord(ch)
            if cp > 0xFFFF:
                sys.stderr.write('%s: character U+%04X is above U+FFFF\n' % (path, cp))
                raise FontError()
            if cp < 0x20 or 0x7F <= cp < 0xA0:
                continue
            wanted.add(cp)
    return wanted


def parse_bdf(path, wanted):
    glyphs = {}  # codepoint -> (advance, rows[12])
    remaining = set(wanted)
    with open(path, 'r', encoding='latin-1') as f:
        in_char = False
        codepoint = None
        advance = 0
        bbx = None
        bitmap = []
        in_bitmap = False
        for line in f:
            line = line.rstrip('\n').rstrip('\r')
            parts = line.split()
            if not parts:
                continue
            key = parts[0]
            if key == 'STARTCHAR':
                in_char = True
                codepoint = None
                advance = 0
                bbx = None
                bitmap = []
                in_bitmap = False
            elif key == 'ENCODING':
                if len(parts) > 1:
                    codepoint = int(parts[1])
            elif key == 'DWIDTH':
                if len(parts) > 1:
                    advance = int(parts[1])
            elif key == 'BBX':
                if len(parts) >= 5:
                    bbx = (int(parts[1]), int(parts[2]),
                           int(parts[3]), int(parts[4]))
            elif key == 'BITMAP':
                in_bitmap = True
            elif key == 'ENDCHAR':
                if in_char and codepoint is not None and codepoint in remaining:
                    if bbx is None:
                        raise FontError(
                            'glyph U+%04X has no BBX' % codepoint)
                    rows = build_cell(codepoint, advance, bbx, bitmap)
                    glyphs[codepoint] = (advance, rows)
                    remaining.discard(codepoint)
                in_char = False
                in_bitmap = False
            elif in_bitmap:
                bitmap.append(parts[0])
    return glyphs, remaining


def build_cell(codepoint, advance, bbx, bitmap):
    w, h, xoff, yoff = bbx
    rows = [0] * 12
    for i in range(h):
        if i >= len(bitmap):
            break
        hexrow = bitmap[i]
        # Left-aligned, padded to byte boundary; bit 0 of first digit is MSB.
        nbits = len(hexrow) * 4
        value = int(hexrow, 16) if hexrow else 0
        for j in range(w):
            bit = (value >> (nbits - 1 - j)) & 1
            if not bit:
                continue
            fy = yoff + h - 1 - i
            cell_row = 9 - fy
            cell_col = xoff + j
            if cell_row < 0 or cell_row > 11 or cell_col < 0 or cell_col > 15:
                raise FontError(
                    'glyph U+%04X pixel outside cell ' +
                    '(row %d, col %d)' % (codepoint, cell_row, cell_col))
            rows[cell_row] |= (1 << (15 - cell_col))
    return rows


def render(glyphs):
    out = []
    out.append('/* Generated by tools/gen_font.py. Do not edit. */\n')
    out.append('#include "font.h"\n')
    out.append('\n')
    out.append('const Glyph FONT_GLYPHS[] = {\n')
    for cp in sorted(glyphs):
        advance, rows = glyphs[cp]
        rowstr = ', '.join('0x%04X' % r for r in rows)
        out.append('    {0x%04X, %d, {%s}},\n' % (cp, advance, rowstr))
    out.append('};\n')
    out.append('\n')
    out.append(
        'const int FONT_GLYPH_COUNT = '
        'sizeof FONT_GLYPHS / sizeof FONT_GLYPHS[0];\n')
    return ''.join(out)


def main(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument('--bdf', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('strings', nargs='+')
    args = parser.parse_args(argv)

    try:
        wanted = collect_chars(args.strings)
    except FontError:
        return 1

    ascii_set = set(range(0x20, 0x7F))
    wanted |= ascii_set

    try:
        glyphs, missing = parse_bdf(args.bdf, wanted)
        if missing:
            for cp in sorted(missing):
                sys.stderr.write('missing glyph U+%04X (%r)\n' % (cp, chr(cp)))
            return 1
    except FontError as e:
        sys.stderr.write('error: %s\n' % e)
        return 1

    content = render(glyphs)
    try:
        with open(args.out, 'r', encoding='utf-8') as f:
            old = f.read()
    except (OSError, UnicodeDecodeError):
        old = None
    if old != content:
        with open(args.out, 'w', encoding='utf-8') as f:
            f.write(content)

    print('%s: %d glyphs, %d files read.' %
          (args.out, len(glyphs), len(args.strings)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
