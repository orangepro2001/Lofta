void palette_build(uint8_t out[256][3], const int32_t tint[3])
{
    int i, ch;

    memset(out, 0, 256 * 3);
    for (i = 0; i < PAL_COLORS; i++) {
        for (ch = 0; ch < 3; ch++) {
            int32_t v = BASE[i][ch];

            if (i >= PAL_TINT_FROM && i < PAL_TINT_END)
                v = v * tint[ch] / 256;
            out[i][ch] = (uint8_t)(v > 255 ? 255 : v);
        }
    }
}
